"""Run every metric and test once and collect the results.

`run()` returns a dict that the charts, the deck, the findings summary and the
tests all read from, so there is exactly one source for every published number.
"""
import pandas as pd

from . import config as c
from . import metrics as m
from . import stats as s
from .clean import load_clean

SCENARIO_HIRE_SHARES = {"Current hiring mix": None, "5% of hires": 0.05, "8% of hires": 0.08}


def run(df=None):
    df = load_clean() if df is None else df
    r = {"df": df}
    snap = m.active_on(df, c.SNAPSHOT)
    r["headcount"] = len(snap)
    r["fte"] = snap["fte"].sum()
    r["by_division"] = m.headcount_summary(df)
    r["headcount_trend"] = m.headcount_trend(df)
    r["turnover_trend"] = m.turnover_trend(df)
    r["turnover_division"] = m.turnover(df, c.REPORT_YEARS[-1], by="division")

    py = s.person_years(df)
    r["person_years"] = py
    r["resignation_rate_pooled"] = py["resigned"].mean()
    r["resignation_by_division"] = py.groupby("division")["resigned"].mean()
    r["resignation_by_tenure"] = py.groupby("tenure_band", observed=True)["resigned"].agg(["mean", "size"])
    r["chi_square"] = s.chi_square_employment_type(py)
    r["digital_vs_rest"] = s.two_proportion(py)
    r["model"], r["odds_ratios"] = s.resignation_model(py)

    r["gender_by_level"] = m.gender_by_level(df)
    r["senior"] = m.women_in_senior_roles(df)
    r["pay_gap"] = m.gender_pay_gap(df)

    hist = m.indigenous_representation(df)
    r["indigenous"] = hist
    now = hist.iloc[-1]
    latest = r["turnover_trend"].iloc[-1]
    hires = df[df["start_date"].dt.year == c.REPORT_YEARS[-1]]
    current_hire_share = (hires["indigenous_status"] == c.INDIGENOUS_YES).mean()
    growth = (r["headcount_trend"]["headcount"].iloc[-1] / r["headcount_trend"]["headcount"].iloc[0]) ** (
        1 / (len(r["headcount_trend"]) - 1)) - 1
    r["scenario_inputs"] = {"headcount": int(now["headcount"]), "identified": int(now["identified"]),
                            "separation_rate": round(float(latest["total_rate"]), 3),
                            "growth_rate": round(float(growth), 3),
                            "current_hire_share": round(float(current_hire_share), 3)}
    si = r["scenario_inputs"]
    r["scenarios"] = {
        label: s.representation_scenario(si["headcount"], si["identified"], si["separation_rate"],
                                         si["growth_rate"], si["current_hire_share"] if share is None else share)
        for label, share in SCENARIO_HIRE_SHARES.items()}

    r["age_profile"] = m.age_profile(df)
    r["retirement"] = s.retirement_exposure(df)
    return r


def years_to_target(scenario):
    hit = scenario[scenario["share"] >= c.INDIGENOUS_TARGET]
    return None if hit.empty else int(hit["year"].iloc[0])


def write_tables(r):
    c.TABLES.mkdir(parents=True, exist_ok=True)
    r["by_division"].to_csv(c.TABLES / "headcount_by_division.csv")
    r["turnover_trend"].round(4).to_csv(c.TABLES / "turnover_trend.csv")
    r["odds_ratios"].round(4).to_csv(c.TABLES / "resignation_odds_ratios.csv")
    r["pay_gap"]["by_level"].round(4).to_csv(c.TABLES / "pay_gap_by_level.csv")
    r["indigenous"].round(4).to_csv(c.TABLES / "indigenous_representation.csv")
    r["retirement"].round(4).to_csv(c.TABLES / "retirement_exposure.csv")


def findings_markdown(r):
    t = r["turnover_trend"]
    y0, y1 = c.REPORT_YEARS[0], c.REPORT_YEARS[-1]
    pg, sen, ind = r["pay_gap"], r["senior"], r["indigenous"].iloc[-1]
    d, chi, orr = r["digital_vs_rest"], r["chi_square"], r["odds_ratios"]
    ret = r["retirement"]
    top = ret.index[0]
    sc = {k: years_to_target(v) for k, v in r["scenarios"].items()}

    def yrs(v):
        return f"reaches the target in about {v} years" if v else "does not reach the target within 10 years"

    return f"""# Key findings - {c.UNIVERSITY} workforce, as at {c.SNAPSHOT:%d %B %Y}

*Generated by `run_pipeline.py`. All data is synthetic.*

**Workforce size.** {r['headcount']:,} staff ({r['fte']:,.0f} FTE), up from {r['headcount_trend']['headcount'].iloc[0]:,} at the end of {y0 - 1}.

**Turnover.** Total separation rate for non-casual staff was {t.loc[y1, 'total_rate']:.1%} in {y1} ({t.loc[y0, 'total_rate']:.1%} in {y0}); the resignation rate was {t.loc[y1, 'voluntary_rate']:.1%}.

**Who resigns.** Resignation is associated with employment type (chi-square = {chi['chi2']:.1f}, df = {chi['dof']}, p < 0.001, Cramer's V = {chi['cramers_v']:.2f} - a real but small effect). Holding other factors constant, fixed-term staff have {orr.loc['Fixed-term (vs ongoing)', 'odds_ratio']:.2f}x the odds of resigning, staff with under two years' service {orr.loc['Tenure under 2 yrs (vs 5+ yrs)', 'odds_ratio']:.2f}x, and Digital & Technology staff {orr.loc['Digital & Technology (vs other areas)', 'odds_ratio']:.2f}x. Gender and staff group are not significant at the 5% level.

**Digital & Technology.** Pooled {y0}-{y1} resignation rate of {d['rate_group']:.1%} against {d['rate_rest']:.1%} elsewhere: a difference of {d['diff'] * 100:.1f} percentage points (95% CI {d['ci_low'] * 100:.1f} to {d['ci_high'] * 100:.1f}).

**Gender.** Women are {sen['women_share_all']:.0%} of staff but {sen['women_share_senior']:.0%} of senior staff (Level D/E and HEW 10+). The overall gender pay gap is {pg['overall']:.1%}; comparing like with like (same classification) it is {pg['like_for_like']:.1%}. Around {pg['structural'] / pg['overall']:.0%} of the gap is therefore structural - who holds senior roles - rather than unequal pay at the same level.

**Aboriginal and Torres Strait Islander representation.** {ind['share']:.1%} of headcount (95% CI {ind['ci_low']:.1%} to {ind['ci_high']:.1%}) against a {c.INDIGENOUS_TARGET:.0%} target; {ind['not_disclosed_share']:.1%} of staff have not disclosed. At the current hiring mix ({r['scenario_inputs']['current_hire_share']:.1%} of hires) representation {yrs(sc['Current hiring mix'])}; at 5% of hires it {yrs(sc['5% of hires'])}; at 8% it {yrs(sc['8% of hires'])}.

**Retirement exposure.** {ret.loc[top, 'share']:.0%} of ongoing staff in the {top} ({int(ret.loc[top, 'reaching_65'])} people) reach 65 within five years, against {ret['reaching_65'].sum() / ret['ongoing_headcount'].sum():.0%} university-wide.
"""

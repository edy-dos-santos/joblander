"""Run every metric and test once; charts, deck, workbook tests and the written summary all read this dict."""
import numpy as np

from . import config as c
from . import data
from . import metrics as m


def run():
    comp, move, notes = data.load()
    f = notes["focus"]
    t = m.league(comp, move)
    r = {"comp": comp, "move": move, "notes": notes, "focus": f, "league": t,
         "scorecard": m.scorecard(t, f), "tiers": m.tiers(comp, f),
         "trend": m.trend(comp, move, f, notes["balanced_panel"])}
    r["funnel_senior"], r["sector_senior"] = m.funnel(t, "women_senior", "senior")
    r["funnel_mgr"], r["sector_mgr"] = m.funnel(t, "women_managers", "managers")
    r["senior_test"] = m.focus_vs_rest(t, f, "women_senior", "senior")
    r["mgr_test"] = m.focus_vs_rest(t, f, "women_managers", "managers")
    r["tier_test"] = m.gender_by_tier_test(comp, f)
    r["promo_pooled"] = m.promotion_parity_test(comp, move, f)
    r["promo_by_year"] = {y: m.promotion_parity_test(comp, move, f, [y]) for y in c.YEARS}
    r["parity"] = m.parity_arithmetic(t, f)

    # Sensitivity: does the senior-management result survive a narrower definition of "senior"?
    d = comp[comp["reporting_year"] == c.LATEST]
    sens = {}
    for label, tiers in [("All tiers above 'Other managers' (headline)", c.SENIOR_TIERS),
                         ("Executives, KMP and CEO only", c.SENIOR_TIERS[:3]),
                         ("Senior managers only", ["Senior managers"])]:
        x = d[d["occupation"].isin(tiers)]
        fx, rx = x[x["university"] == f], x[x["university"] != f]
        share = lambda g: g.loc[g["gender"] == "Women", "n_employees"].sum() / g["n_employees"].sum()  # noqa: E731
        sens[label] = {"focus": share(fx), "rest": share(rx), "focus_n": int(fx["n_employees"].sum())}
    r["sensitivity"] = sens
    r["mix"] = d.assign(group=np.where(d["university"] == f, c.FOCUS_SHORT, "All other universities")).pivot_table(
        index="group", columns="employment_type", values="n_employees", aggfunc="sum")[c.EMPLOYMENT_TYPES]
    r["mix"] = r["mix"].div(r["mix"].sum(axis=1), axis=0).loc[[c.FOCUS_SHORT, "All other universities"]]
    return r


def findings_markdown(r):
    f, s, t = c.FOCUS_SHORT, r["scorecard"], r["league"]
    row = t.loc[r["focus"]]
    ti, st, pp, py = r["tiers"], r["senior_test"], r["promo_pooled"], r["promo_by_year"][c.LATEST]
    tr = r["trend"].set_index(["metric", "year"])
    fun = r["funnel_senior"].loc[r["focus"]]
    y0, y1 = c.YEARS[0], c.YEARS[-1]
    mgr_share = t["manager_share"]
    par = r["parity"]
    return f"""# Key findings - {f} against {len(t) - 1} other Australian universities, {y1}

*Generated by `run_pipeline.py` from WGEA public data (CC BY 3.0 AU). Independent analysis; not affiliated with or endorsed by QUT or WGEA.*

**1. Women are well represented in management overall, but not at the top.** Women are {row['women_share']:.1%} of {f}'s {int(row['headcount']):,} employees and {row['women_mgr_share']:.1%} of its managers (sector: {s.loc['women_mgr_share', 'sector_pooled']:.1%}; difference not statistically significant, p = {r['mgr_test']['p']:.2f}). Within management the picture splits: {ti.loc['Other managers', 'focus_share']:.0%} of 'other managers' are women, against {ti.loc['Senior managers', 'focus_share']:.0%} of senior managers and {ti.loc['Other Executives and General Managers', 'focus_share']:.0%} of executives and general managers. Gender and level are not independent (chi-square = {r['tier_test']['chi2']:.1f}, df = {r['tier_test']['dof']}, p < 0.001; Cramer's V = {r['tier_test']['cramers_v']:.2f}, a small effect).

**2. Senior management is where {f} sits below the sector.** Women hold {st['focus']:.1%} of {st['n_focus']} senior management roles, against {st['rest']:.1%} at other universities: {abs(st['diff']) * 100:.1f} points lower (95% CI {abs(st['ci_high']) * 100:.1f} to {abs(st['ci_low']) * 100:.1f}; p = {st['p']:.3f}), ranking {s.loc['women_senior_share', 'rank']} of {s.loc['women_senior_share', 'of']}. This is suggestive rather than conclusive: on a funnel plot {f} is outside the 95% control limits but inside the 99.8% limits (z = {fun['z']:.1f}), and with {len(t)} universities one or two would fall outside 95% by chance.

**3. The gap to the sector has widened, because the sector moved and {f} did not.** {f}'s senior-management share was {tr.loc[('women_senior_share', y0), 'focus']:.1%} in {y0} and {tr.loc[('women_senior_share', y1), 'focus']:.1%} in {y1}; the sector went from {tr.loc[('women_senior_share', y0), 'sector']:.1%} to {tr.loc[('women_senior_share', y1), 'sector']:.1%}.

**4. A one-year dip in promotions is not evidence of a problem.** In {y1} women received {py['share']:.0%} of {py['promotions']} promotions against {py['expected']:.0%} of non-casual staff (parity ratio {py['parity']:.2f}, rank {s.loc['promo_parity', 'rank']} of {s.loc['promo_parity', 'of']}). Pooled over three years the ratio is {pp['parity']:.2f} on {pp['promotions']} promotions and is consistent with parity (exact binomial p = {pp['p']:.2f}).

**5. Scale of the task.** At its current size, {f} would reach the sector average with {par.loc['Sector average', 'additional']} more women in senior management, and 50% with {par.loc['50%', 'additional']}.

**6. Read every cross-university comparison with one caveat in mind.** Employers decide how their own roles map to WGEA's manager categories. {f} reports {row['manager_share']:.0%} of employees as managers; the median university reports {mgr_share.median():.0%} and the range is {mgr_share.min():.0%} to {mgr_share.max():.0%}. "Senior management" therefore does not mean the same set of roles everywhere. The within-{f} pattern in finding 1 does not depend on this; the sector comparison in finding 2 does.

**Workforce mix (context).** {row['casual_share']:.0%} of {f}'s headcount is casual (sector {s.loc['casual_share', 'sector_pooled']:.0%}) and {row['contract_share']:.0%} fixed-term ({s.loc['contract_share', 'sector_pooled']:.0%}). Men took {row['men_carer_share']:.0%} of primary carer's leave ({s.loc['men_carer_share', 'sector_pooled']:.0%} sector-wide).
"""
